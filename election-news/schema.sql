CREATE TABLE IF NOT EXISTS items(id INTEGER PRIMARY KEY AUTOINCREMENT,url TEXT UNIQUE NOT NULL,source TEXT NOT NULL,title TEXT,status TEXT NOT NULL,created_at INTEGER,uploaded_at INTEGER,file TEXT,error TEXT,attempts INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS sources(id TEXT PRIMARY KEY,last_ok INTEGER,error TEXT);
CREATE TABLE IF NOT EXISTS locks(id INTEGER PRIMARY KEY,until INTEGER NOT NULL);
INSERT OR IGNORE INTO locks(id,until) VALUES(1,0);
CREATE TABLE IF NOT EXISTS collector_checks(url TEXT PRIMARY KEY,status TEXT NOT NULL,checked_at INTEGER NOT NULL,error TEXT);
